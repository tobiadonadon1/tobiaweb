#!/usr/bin/env node
/**
 * Regenerate the 98¢ Trade backtest chart's data from the product's own
 * trade-level results.
 *
 *   node scripts/backtest-chart-data.mjs ~/Desktop/JevTrader/the-98c-trade/research/shipped_backtest.csv \
 *     > components/superhuman/material/product/backtest-data.ts
 *
 * The chart draws every trade as a dot, grouped by the quarter it settled in,
 * so all it needs is each quarter's count, its average return, and where in
 * that quarter (in settlement order) each losing trade fell. Nothing is
 * rounded until it is printed, and nothing is added.
 */
import { readFileSync } from "node:fs";

const file = process.argv[2];
if (!file) {
  console.error("usage: node scripts/backtest-chart-data.mjs <shipped_backtest.csv>");
  process.exit(1);
}

const [header, ...lines] = readFileSync(file, "utf8").trim().split(/\r?\n/);
const cols = header.split(",");
const at = (name) => cols.indexOf(name);
const rows = lines
  .map((l) => l.split(","))
  .map((c) => ({
    id: Number(c[at("id")]),
    ret: Number(c[at("ret")]),
    lost: c[at("fav_fail")] === "True",
    end: c[at("end")],
  }))
  .sort((a, b) => (a.end < b.end ? -1 : a.end > b.end ? 1 : a.id - b.id));

const quarters = new Map();
for (const r of rows) {
  const year = r.end.slice(0, 4);
  const q = Math.floor((Number(r.end.slice(5, 7)) - 1) / 3) + 1;
  const key = `${year} Q${q}`;
  if (!quarters.has(key)) quarters.set(key, { key, year: Number(year), q, rows: [], last: r.end });
  const bucket = quarters.get(key);
  bucket.rows.push(r);
  bucket.last = r.end;
}

const out = [...quarters.values()].map((b) => ({
  year: b.year,
  quarter: b.q,
  trades: b.rows.length,
  avgReturnPct: Math.round((1e4 * b.rows.reduce((s, r) => s + r.ret, 0)) / b.rows.length) / 100,
  lostAt: b.rows.flatMap((r, i) => (r.lost ? [i] : [])),
  through: b.last.slice(0, 10),
}));

const total = rows.length;
const lost = rows.filter((r) => r.lost).length;
const avg = Math.round((1e4 * rows.reduce((s, r) => s + r.ret, 0)) / total) / 100;

console.log(`/**
 * GENERATED by scripts/backtest-chart-data.mjs from the product's
 * research/shipped_backtest.csv. Do not edit by hand; regenerate.
 *
 * Every trade The 98¢ Trade would have made on Polymarket, as shipped, grouped
 * by the quarter the market settled in. \`lostAt\` is the position of each
 * losing trade within its quarter, in settlement order.
 */
export type BacktestQuarter = {
  year: number;
  quarter: number;
  trades: number;
  /** Average return per trade, in percent, before real-world fill effects. */
  avgReturnPct: number;
  lostAt: number[];
  /** The last settlement date in the data for this quarter. */
  through: string;
};

export const BACKTEST_TOTAL = { trades: ${total}, lost: ${lost}, avgReturnPct: ${avg} } as const;

export const BACKTEST_QUARTERS: BacktestQuarter[] = ${JSON.stringify(out, null, 2)};`);
